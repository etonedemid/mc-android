#!/usr/bin/env python3
# gen-font.py JAR - Minecraft's own font (textures/font/ascii.png, ASCII 32..126) as tables for the on-screen keyboards:
# app/mcfont.h here (8 row bytes per glyph, leftmost pixel in bit 7, then its advance) and McFont.java for the 26.3 app.
import io, sys, zipfile
from PIL import Image
img = Image.open(io.BytesIO(zipfile.ZipFile(sys.argv[1]).read('assets/minecraft/textures/font/ascii.png'))).convert('RGBA')
cell = img.width // 16
rows, adv = [], []
for c in range(32, 127):
    gx, gy = c % 16 * cell, c // 16 * cell
    bits, right = [], -1
    for y in range(8):
        b = 0
        for x in range(8):
            if img.getpixel((gx + x * cell // 8, gy + y * cell // 8))[3] > 127: b |= 0x80 >> x; right = max(right, x)
        bits.append(b)
    rows.append(bits); adv.append(4 if c == 32 else right + 2)   # as the game: last column used, plus a pixel of space
with open('app/mcfont.h', 'w') as f:
    f.write('// mcfont.h - Minecraft\'s font, ASCII 32..126 (generated by tools/gen-font.py from the game\'s ascii.png)\n')
    f.write('static const unsigned char MCFONT[95][8] = {\n')
    for b in rows: f.write('    { ' + ', '.join('0x%02x' % v for v in b) + ' },\n')
    f.write('};\nstatic const unsigned char MCFONT_ADV[95] = { ' + ', '.join(map(str, adv)) + ' };\n')
with open(sys.argv[2], 'w') as f:
    f.write('package com.etonedemid.mc26;\n\n// Minecraft\'s font, ASCII 32..126 (generated by ~/mc-android/tools/gen-font.py from the game\'s ascii.png): 8 row\n')
    f.write('// bytes per glyph, leftmost pixel in bit 7, and each glyph\'s advance\nfinal class McFont {\n    static final int[] ROWS = {\n')
    for b in rows: f.write('        ' + ', '.join('0x%02x' % v for v in b) + ',\n')
    f.write('    };\n    static final int[] ADV = { ' + ', '.join(map(str, adv)) + ' };\n}\n')
